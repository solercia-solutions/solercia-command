@skip_no_db
def test_upgrade_adds_nullable_columns_without_touching_existing_rows() -> None:
    """Escenario 6: ``alembic upgrade 0025`` agrega columnas nulables sin
    alterar las filas ya existentes."""

    test_database_url = os.environ["TEST_DATABASE_URL"]
    with _disposable_database(test_database_url, _MIGRATION_DB_NAME) as (dsn, cfg):
        command.upgrade(cfg, "0024")
        org_id = asyncio.run(_seed_organization(dsn))
        project_id = asyncio.run(_seed_project(dsn, org_id, "UPG"))
        task_id = asyncio.run(_insert_task(dsn, project_id))

        command.upgrade(cfg, "0025")

        async def _assert() -> None:
            conn = await asyncpg.connect(dsn=dsn)
            try:
                columns = await conn.fetch(
                    "SELECT column_name, is_nullable FROM information_schema.columns "
                    "WHERE table_name = 'tasks' "
                    "AND column_name IN ('source', 'external_key')"
                )
                by_name = {row["column_name"]: row["is_nullable"] for row in columns}
                assert by_name == {"source": "YES", "external_key": "YES"}

                row = await conn.fetchrow(
                    "SELECT source, external_key FROM tasks WHERE id = $1", task_id
                )
                assert row is not None
                assert row["source"] is None
                assert row["external_key"] is None
            finally:
                await conn.close()

        asyncio.run(_assert())


