def _sync_dsn(url: str) -> str:
    return url.replace("postgresql+asyncpg://", "postgresql://")


def _admin_dsn(test_database_url: str) -> str:
    dsn = _sync_dsn(test_database_url)
    base, _, _ = dsn.rpartition("/")
    return f"{base}/postgres"


def _db_dsn(test_database_url: str, db_name: str) -> str:
    dsn = _sync_dsn(test_database_url)
    base, _, _ = dsn.rpartition("/")
    return f"{base}/{db_name}"


async def _recreate_database(test_database_url: str, db_name: str) -> None:
    admin_conn = await asyncpg.connect(dsn=_admin_dsn(test_database_url))
    try:
        await admin_conn.execute(f'DROP DATABASE IF EXISTS "{db_name}" WITH (FORCE)')
        await admin_conn.execute(f'CREATE DATABASE "{db_name}"')
    finally:
        await admin_conn.close()


async def _drop_database(test_database_url: str, db_name: str) -> None:
    admin_conn = await asyncpg.connect(dsn=_admin_dsn(test_database_url))
    try:
        await admin_conn.execute(f'DROP DATABASE IF EXISTS "{db_name}" WITH (FORCE)')
    finally:
        await admin_conn.close()


def _alembic_config(sqlalchemy_url: str) -> Config:
    cfg = Config(str(BACKEND_DIR / "alembic.ini"))
    cfg.set_main_option("script_location", str(BACKEND_DIR / "alembic"))
    cfg.set_main_option("sqlalchemy.url", sqlalchemy_url)
    return cfg


def _run_against(async_url: str) -> Config:
    from app.config import settings

    settings.DATABASE_URL = async_url
    return _alembic_config(async_url)


@contextlib.contextmanager
def _disposable_database(test_database_url: str, db_name: str) -> Iterator[tuple[str, Config]]:
    """Crea, cede y destruye una base desechable con su ``Config`` de Alembic
    ya apuntada — misma disciplina try/finally de ``test_migration_project_
    kind.py``, parametrizada por nombre para reutilizarse entre las dos bases
    que necesita ``test_create_all_and_migration_declare_the_same_anchor_ddl``.
    """

    from app.config import settings

    original_url = settings.DATABASE_URL
    try:
        asyncio.run(_recreate_database(test_database_url, db_name))
        dsn = _db_dsn(test_database_url, db_name)
        async_url = dsn.replace("postgresql://", "postgresql+asyncpg://")
        cfg = _run_against(async_url)
        yield dsn, cfg
    finally:
        settings.DATABASE_URL = original_url
        asyncio.run(_drop_database(test_database_url, db_name))


