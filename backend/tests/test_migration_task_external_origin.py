async def _seed_organization(dsn: str) -> uuid.UUID:
    org_id = uuid.uuid4()
    conn = await asyncpg.connect(dsn=dsn)
    try:
        await conn.execute(
            "INSERT INTO organizations "
            "(id, name, slug, is_active, working_hours_per_day, working_days) "
            "VALUES ($1, $2, $3, true, 8, $4)",
            org_id,
            "Task External Origin Org",
            f"task-external-origin-org-{uuid.uuid4().hex[:12]}",
            [1, 2, 3, 4, 5],
        )
    finally:
        await conn.close()
    return org_id


async def _seed_project(dsn: str, organization_id: uuid.UUID, code: str) -> uuid.UUID:
    project_id = uuid.uuid4()
    conn = await asyncpg.connect(dsn=dsn)
    try:
        await conn.execute(
            "INSERT INTO projects "
            "(id, name, methodology, status, code, task_counter, "
            " organization_id, is_active, project_kind) "
            "VALUES ($1, $2, 'planner', 'active', $3, 0, $4, true, 'proyecto')",
            project_id,
            f"Proyecto {code}",
            code,
            organization_id,
        )
    finally:
        await conn.close()
    return project_id


async def _insert_task(
    dsn: str,
    project_id: uuid.UUID,
    *,
    source: str | None = None,
    external_key: str | None = None,
    is_active: bool = True,
) -> uuid.UUID:
    """Inserta una tarea vía SQL crudo. Cuando ``source`` y ``external_key``
    son ambos ``None`` omite esas dos columnas del INSERT, de modo que el
    mismo helper sirve para sembrar antes de la migración 0025 (cuando las
    columnas todavía no existen) y después de ella."""

    task_id = uuid.uuid4()
    conn = await asyncpg.connect(dsn=dsn)
    try:
        if source is None and external_key is None:
            await conn.execute(
                "INSERT INTO tasks "
                "(id, project_id, title, task_type, status, priority, "
                " task_order, risk_flag, is_active) "
                "VALUES ($1, $2, 'Tarea sembrada', 'task', 'Backlog', 'medium', "
                " 0, false, $3)",
                task_id,
                project_id,
                is_active,
            )
        else:
            await conn.execute(
                "INSERT INTO tasks "
                "(id, project_id, title, task_type, status, priority, "
                " task_order, risk_flag, is_active, source, external_key) "
                "VALUES ($1, $2, 'Tarea anclada', 'task', 'Backlog', 'medium', "
                " 0, false, $3, $4, $5)",
                task_id,
                project_id,
                is_active,
                source,
                external_key,
            )
    finally:
        await conn.close()
    return task_id


async def _create_all_schema(async_url: str) -> None:
    import app.db_init  # noqa: F401 — puebla Base.metadata con todos los modelos
    from app.database import Base

    engine = create_async_engine(async_url, poolclass=NullPool, future=True)
    try:
        async with engine.begin() as conn:
            await conn.execute(text("CREATE EXTENSION IF NOT EXISTS pg_trgm"))
            await conn.run_sync(Base.metadata.create_all)
    finally:
        await engine.dispose()


async def _index_def(dsn: str, index_name: str) -> str:
    conn = await asyncpg.connect(dsn=dsn)
    try:
        return await conn.fetchval("SELECT pg_get_indexdef($1::regclass)", index_name)
    finally:
        await conn.close()


async def _constraint_def(dsn: str, constraint_name: str) -> str:
    conn = await asyncpg.connect(dsn=dsn)
    try:
        return await conn.fetchval(
            "SELECT pg_get_constraintdef(oid) FROM pg_constraint WHERE conname = $1",
            constraint_name,
        )
    finally:
        await conn.close()


