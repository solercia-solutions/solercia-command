@skip_no_db
def test_create_all_and_migration_declare_the_same_anchor_ddl() -> None:
    """Escenarios 8 y 9: ``Base.metadata.create_all`` y ``alembic upgrade
    0025`` declaran el mismo índice único parcial y el mismo ``CHECK``.
    ``alembic check`` (1.14.0) NO compara ``postgresql_where`` ni ninguna
    ``CheckConstraint`` (D-B) — esta prueba es el gate real del espejado."""

    test_database_url = os.environ["TEST_DATABASE_URL"]
    with _disposable_database(test_database_url, _MIGRATION_DB_NAME) as (
        migrated_dsn,
        cfg,
    ):
        command.upgrade(cfg, "0025")

        with _disposable_database(test_database_url, _DDL_MODEL_DB_NAME) as (
            model_dsn,
            _model_cfg,
        ):
            model_async_url = _db_dsn(test_database_url, _DDL_MODEL_DB_NAME).replace(
                "postgresql://", "postgresql+asyncpg://"
            )
            asyncio.run(_create_all_schema(model_async_url))

            migrated_index = asyncio.run(_index_def(migrated_dsn, _ANCHOR_INDEX_NAME))
            model_index = asyncio.run(_index_def(model_dsn, _ANCHOR_INDEX_NAME))
            assert migrated_index == model_index

            migrated_check = asyncio.run(_constraint_def(migrated_dsn, _ANCHOR_CHECK_NAME))
            model_check = asyncio.run(_constraint_def(model_dsn, _ANCHOR_CHECK_NAME))
            assert migrated_check == model_check


