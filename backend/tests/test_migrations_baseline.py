"""Guard test: the Alembic baseline must be equivalent to the ORM models (R4).

Runs against a disposable database (created and dropped by this test) instead
of ``solercia_test`` so it never collides with the ``create_all``-based
fixtures the rest of the suite uses (see design.md, "Brecha residual
aceptada"): the two paths that build a test schema — Alembic migrations here,
``create_all`` in ``conftest.py`` — are verified independently.
"""

import asyncio
import os
from pathlib import Path

import asyncpg
import pytest
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected

from alembic import command

try:
    from tests.conftest import skip_no_db
except ImportError:
    skip_no_db = pytest.mark.skip(reason="conftest not found")

BACKEND_DIR = Path(__file__).resolve().parent.parent
_MIGRATIONS_DB_NAME = "solercia_test_migrations"

# Core tables every ORM model registers on Base.metadata (db_init.py imports
# every model module). A handful is enough to prove the baseline actually
# created the schema, without duplicating the full model inventory here.
_EXPECTED_TABLES = {
    "organizations",
    "organization_members",
    "users",
    "projects",
    "tasks",
    "sprints",
    "roles",
    "dependencies",
}


def _sync_dsn(url: str) -> str:
    """Strip the ``+asyncpg`` SQLAlchemy dialect marker for a plain asyncpg DSN."""

    return url.replace("postgresql+asyncpg://", "postgresql://")


def _admin_dsn(test_database_url: str) -> str:
    """Return the maintenance-DB DSN (same server, ``postgres`` database)."""

    dsn = _sync_dsn(test_database_url)
    base, _, _ = dsn.rpartition("/")
    return f"{base}/postgres"


def _migrations_db_dsn(test_database_url: str) -> str:
    """Return the disposable migrations-check DSN on the same server."""

    dsn = _sync_dsn(test_database_url)
    base, _, _ = dsn.rpartition("/")
    return f"{base}/{_MIGRATIONS_DB_NAME}"


async def _recreate_migrations_database(test_database_url: str) -> None:
    """Drop (if present) and re-create the disposable migrations database."""

    admin_conn = await asyncpg.connect(dsn=_admin_dsn(test_database_url))
    try:
        await admin_conn.execute(
            f'DROP DATABASE IF EXISTS "{_MIGRATIONS_DB_NAME}" WITH (FORCE)'
        )
        await admin_conn.execute(f'CREATE DATABASE "{_MIGRATIONS_DB_NAME}"')
    finally:
        await admin_conn.close()


async def _drop_migrations_database(test_database_url: str) -> None:
    """Best-effort cleanup so the disposable database never lingers."""

    admin_conn = await asyncpg.connect(dsn=_admin_dsn(test_database_url))
    try:
        await admin_conn.execute(
            f'DROP DATABASE IF EXISTS "{_MIGRATIONS_DB_NAME}" WITH (FORCE)'
        )
    finally:
        await admin_conn.close()


async def _list_tables(dsn: str) -> set[str]:
    conn = await asyncpg.connect(dsn=dsn)
    try:
        rows = await conn.fetch(
            "SELECT tablename FROM pg_tables WHERE schemaname = 'public'"
        )
        return {row["tablename"] for row in rows}
    finally:
        await conn.close()


# The 5 pg_trgm GIN indexes migration 0008 must create (change
# 10-busqueda-global, design.md "Índices GIN").
_EXPECTED_GIN_INDEXES = {
    "ix_tasks_title_trgm",
    "ix_tasks_description_trgm",
    "ix_projects_name_trgm",
    "ix_projects_description_trgm",
    "ix_task_comments_body_trgm",
}


async def _list_gin_indexes(dsn: str) -> set[str]:
    """Return the names of every index using the ``gin`` access method."""

    conn = await asyncpg.connect(dsn=dsn)
    try:
        rows = await conn.fetch(
            "SELECT c.relname AS index_name "
            "FROM pg_class c "
            "JOIN pg_am am ON am.oid = c.relam "
            "WHERE c.relkind = 'i' AND am.amname = 'gin'"
        )
        return {row["index_name"] for row in rows}
    finally:
        await conn.close()


async def _has_extension(dsn: str, name: str) -> bool:
    conn = await asyncpg.connect(dsn=dsn)
    try:
        row = await conn.fetchrow(
            "SELECT 1 FROM pg_extension WHERE extname = $1", name
        )
        return row is not None
    finally:
        await conn.close()


def _alembic_config(sqlalchemy_url: str) -> Config:
    """Build an Alembic ``Config`` pointing at ``sqlalchemy_url``.

    ``alembic/env.py`` overrides ``sqlalchemy.url`` with ``app.config.settings
    .DATABASE_URL`` unconditionally, so the caller must patch that singleton
    before invoking commands built from this config (see ``_run_against``).
    """

    cfg = Config(str(BACKEND_DIR / "alembic.ini"))
    cfg.set_main_option("script_location", str(BACKEND_DIR / "alembic"))
    cfg.set_main_option("sqlalchemy.url", sqlalchemy_url)
    return cfg


def _run_against(async_url: str) -> Config:
    """Point the live app settings at ``async_url`` and return the Alembic config.

    ``app.config.settings`` is a module-level singleton read by ``env.py``; it
    is mutable (no ``frozen=True``), so patching it here redirects Alembic
    without touching environment variables or import order.
    """

    from app.config import settings

    settings.DATABASE_URL = async_url
    return _alembic_config(async_url)


@skip_no_db
def test_alembic_upgrade_head_creates_full_schema() -> None:
    """``alembic upgrade head`` on an empty DB creates every core table (R4)."""

    test_database_url = os.environ["TEST_DATABASE_URL"]
    from app.config import settings

    original_url = settings.DATABASE_URL
    try:
        asyncio.run(_recreate_migrations_database(test_database_url))
        migrations_url = _migrations_db_dsn(test_database_url).replace(
            "postgresql://", "postgresql+asyncpg://"
        )
        cfg = _run_against(migrations_url)
        command.upgrade(cfg, "head")

        tables = asyncio.run(_list_tables(_migrations_db_dsn(test_database_url)))
        missing = _EXPECTED_TABLES - tables
        assert not missing, f"alembic upgrade head no creó: {sorted(missing)}"
    finally:
        settings.DATABASE_URL = original_url
        asyncio.run(_drop_migrations_database(test_database_url))


@skip_no_db
def test_alembic_check_reports_no_diff_after_upgrade() -> None:
    """``alembic check`` on the migrated schema reports zero pending diff (R4)."""

    test_database_url = os.environ["TEST_DATABASE_URL"]
    from app.config import settings

    original_url = settings.DATABASE_URL
    try:
        asyncio.run(_recreate_migrations_database(test_database_url))
        migrations_url = _migrations_db_dsn(test_database_url).replace(
            "postgresql://", "postgresql+asyncpg://"
        )
        cfg = _run_against(migrations_url)
        command.upgrade(cfg, "head")

        try:
            command.check(cfg)
        except AutogenerateDiffsDetected as exc:
            pytest.fail(f"El baseline no coincide con los modelos: {exc}")
    finally:
        settings.DATABASE_URL = original_url
        asyncio.run(_drop_migrations_database(test_database_url))


@skip_no_db
def test_migration_0008_upgrade_creates_gin_indexes() -> None:
    """``alembic upgrade head`` creates the 5 ``pg_trgm`` GIN indexes (change
    10-busqueda-global): ``tasks.title``, ``tasks.description``,
    ``projects.name``, ``projects.description``, ``task_comments.body``.
    """

    test_database_url = os.environ["TEST_DATABASE_URL"]
    from app.config import settings

    original_url = settings.DATABASE_URL
    try:
        asyncio.run(_recreate_migrations_database(test_database_url))
        migrations_url = _migrations_db_dsn(test_database_url).replace(
            "postgresql://", "postgresql+asyncpg://"
        )
        cfg = _run_against(migrations_url)
        command.upgrade(cfg, "head")

        gin_indexes = asyncio.run(
            _list_gin_indexes(_migrations_db_dsn(test_database_url))
        )
        missing = _EXPECTED_GIN_INDEXES - gin_indexes
        assert not missing, (
            f"alembic upgrade head no creó los índices GIN: {sorted(missing)}"
        )
    finally:
        settings.DATABASE_URL = original_url
        asyncio.run(_drop_migrations_database(test_database_url))


@skip_no_db
def test_migration_0008_downgrade_removes_indexes_and_extension() -> None:
    """``alembic downgrade -1`` removes the 5 GIN indexes and drops ``pg_trgm``.

    Asserts the indexes/extension exist right after ``upgrade head`` first
    (precondition) so this test genuinely fails while migration 0008 does
    not exist yet, instead of trivially passing on an empty schema.
    """

    test_database_url = os.environ["TEST_DATABASE_URL"]
    from app.config import settings

    original_url = settings.DATABASE_URL
    try:
        asyncio.run(_recreate_migrations_database(test_database_url))
        migrations_url = _migrations_db_dsn(test_database_url).replace(
            "postgresql://", "postgresql+asyncpg://"
        )
        cfg = _run_against(migrations_url)
        command.upgrade(cfg, "head")

        dsn = _migrations_db_dsn(test_database_url)
        gin_before = asyncio.run(_list_gin_indexes(dsn))
        assert _EXPECTED_GIN_INDEXES <= gin_before, (
            "Precondición: alembic upgrade head debe crear los 5 índices "
            f"GIN antes de poder probar el downgrade (faltan: "
            f"{sorted(_EXPECTED_GIN_INDEXES - gin_before)})"
        )
        assert asyncio.run(_has_extension(dsn, "pg_trgm")), (
            "Precondición: pg_trgm debe estar instalada tras el upgrade"
        )

        command.downgrade(cfg, "-1")

        gin_after = asyncio.run(_list_gin_indexes(dsn))
        remaining = _EXPECTED_GIN_INDEXES & gin_after
        assert not remaining, (
            f"alembic downgrade -1 dejó índices GIN sin eliminar: {sorted(remaining)}"
        )
        assert not asyncio.run(_has_extension(dsn, "pg_trgm")), (
            "alembic downgrade -1 no eliminó la extensión pg_trgm"
        )
    finally:
        settings.DATABASE_URL = original_url
        asyncio.run(_drop_migrations_database(test_database_url))
